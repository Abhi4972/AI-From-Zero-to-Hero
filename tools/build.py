def scripts(page):
    first = page.find("<article"); last = page.rfind("</article>") + 10
    rest = page[:first] + page[last:]
    return [(m.group(1), m.group(2)) for m in re.finditer(r"<script((?:\s[^>]*)?)>(.*?)</script>", rest, re.S)]

def pick(scr, sig, attr=None):
    for a, b in scr:
        if attr and attr in a: return b
        if sig and b.lstrip().startswith(sig): return b
    return None

def js_obj(text, name):
    m = re.search(r"const " + name + r" = (.*?);\n", text, re.S)
    return m.group(1)

